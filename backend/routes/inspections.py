"""Vehicle condition assessment endpoints.

    POST /inspections/dropoff                        staff - capture drop-off photos
    POST /inspections/pickup                         staff - capture pickup photos, compare
    GET  /inspections/<custody_id>                   owner or staff - condition report
    PATCH /inspections/detections/<id>/verification  manager/admin - confirm or reject
    GET  /inspections/demo/scenarios                 staff - the demo catalogue
    POST /inspections/demo                           staff - run the pipeline on synthetic photos

Capture is multipart because that is what a camera produces. The heavy lifting
lives in :mod:`services.inspections` and :mod:`ai.vision`; these handlers only
translate HTTP into service calls, which keeps them short enough to audit.

**Why pickup compares and drop-off does not.** A drop-off set is the baseline;
there is nothing to compare it against yet. Pickup triggers the comparison
automatically, so the report is ready the moment the photos land rather than
waiting for someone to remember to press a button.

Mounted at both ``/api/v1/inspections`` and ``/api/inspections`` -- see
``routes/__init__.py`` for why.
"""

from __future__ import annotations

from flask import Blueprint, request

from models.enums import InspectionStage
from services import inspections
from utils.exceptions import ValidationError
from utils.requests import json_payload
from utils.responses import created, ok
from utils.security import current_user, require_authentication
from utils.validation import validate_uuid

#: Form fields that are not photos. Anything else in the form is ignored rather
#: than rejected, so an older client sending an extra field still works.
MAX_PHOTOS_PER_REQUEST = inspections.MAX_PHOTOS_PER_STAGE


def _files_from_request() -> list:
    """Collect uploaded photos from either ``image`` or ``images``."""
    files = request.files.getlist("images") or []
    single = request.files.get("image")
    if single is not None:
        files = [single, *files]

    if not files:
        raise ValidationError(
            "No image was uploaded. Send one or more files in the 'images' field.",
            details={"field": "images"},
        )
    if len(files) > MAX_PHOTOS_PER_REQUEST:
        raise ValidationError(
            f"At most {MAX_PHOTOS_PER_REQUEST} images per request.",
            details={"count": len(files), "max": MAX_PHOTOS_PER_REQUEST},
        )
    return files


def _form_payload() -> dict:
    """The multipart form fields, with repeated ``angles`` collected as a list."""
    payload: dict = dict(request.form.items())
    angles = request.form.getlist("angles")
    if angles:
        payload["angles"] = angles
    return payload


def _custody_id_from(source: dict) -> str:
    raw = source.get("custody_id") or source.get("custody_session_id")
    if not raw:
        raise ValidationError(
            "'custody_id' is required and must be the custody session's id.",
            details={"field": "custody_id"},
        )
    return validate_uuid(raw, field="custody_id")


def create_inspections_blueprint() -> Blueprint:
    """Build a fresh inspections blueprint (a new instance per app)."""
    blueprint = Blueprint("inspections", __name__)

    @blueprint.post("/dropoff")
    @require_authentication
    def capture_drop_off():
        """Store the drop-off photo set that later comparisons are measured against."""
        actor = current_user()
        custody_id = _custody_id_from(request.form)

        result = inspections.capture_inspection(
            actor,
            custody_id=custody_id,
            stage=InspectionStage.DROP_OFF,
            files=_files_from_request(),
            form=_form_payload(),
        )
        return created(result)

    @blueprint.post("/pickup")
    @require_authentication
    def capture_pickup():
        """Store the pickup photo set and compare it against drop-off.

        The response carries the candidate findings and the rendered comparison
        images, so the reviewing UI has everything it needs in one call.
        """
        actor = current_user()
        custody_id = _custody_id_from(request.form)

        result = inspections.capture_inspection(
            actor,
            custody_id=custody_id,
            stage=InspectionStage.PICKUP,
            files=_files_from_request(),
            form=_form_payload(),
        )
        return created(result)

    @blueprint.get("/demo/scenarios")
    @require_authentication
    def list_demo_scenarios():
        """The synthetic scenarios the demo endpoint can run."""
        current_user()
        return ok(
            {
                "scenarios": inspections.demo_scenarios(),
                "note": (
                    "Demo photographs are generated by OpenCV. Findings produced "
                    "from them are real pipeline output, not canned results."
                ),
            }
        )

    @blueprint.post("/demo")
    @require_authentication
    def run_demo():
        """Run the real pipeline over a synthetic photo pair.

        Stores no inspection and no findings, so it can be run repeatedly
        without polluting custody history.
        """
        actor = current_user()
        payload = json_payload(required=False) or {}
        scenario = payload.get("scenario") or request.args.get("scenario") or "multiple"

        return ok(inspections.run_demo_comparison(actor, scenario=str(scenario)))

    @blueprint.patch("/detections/<detection_id>/verification")
    @require_authentication
    def verify(detection_id: str):
        """Confirm or reject one finding. Manager or administrator only."""
        actor = current_user()
        payload = json_payload()

        status = payload.get("status")
        if not status:
            raise ValidationError(
                "'status' is required: CONFIRMED, REJECTED or UNVERIFIED.",
                details={"field": "status"},
            )

        result = inspections.verify_detection(
            actor,
            detection_id=validate_uuid(detection_id, field="detection_id"),
            status=str(status).upper(),
            notes=payload.get("notes"),
        )
        return ok(result)

    @blueprint.get("/<custody_id>")
    @require_authentication
    def report(custody_id: str):
        """The full condition report: both photo sets, findings, evidence."""
        actor = current_user()
        return ok(
            inspections.get_inspection_report(
                actor, validate_uuid(custody_id, field="custody_id")
            )
        )

    return blueprint


__all__ = ["create_inspections_blueprint"]
