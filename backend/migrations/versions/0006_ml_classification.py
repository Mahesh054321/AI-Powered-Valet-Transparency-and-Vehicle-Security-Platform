    op.add_column(
        "gps_events",
        sa.Column(
            "ml_classification",
            sa.String(16),
            nullable=True,
            comment="NORMAL | SUSPICIOUS from the prototype classifier.",
        ),
    )
    op.add_column(
        "gps_events",
        sa.Column(
            "ml_probability",
            sa.Numeric(4, 3),
            nullable=True,
            comment="P(SUSPICIOUS) as estimated by the prototype model.",
        ),
    )
    op.add_column(
        "gps_events",
        sa.Column(
            "ml_model_version",
            sa.String(64),
            nullable=True,
            comment="Which artifact produced the verdict, so drift is detectable.",
        ),
    )

