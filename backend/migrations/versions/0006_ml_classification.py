down_revision: str | Sequence[str] | None = "0005"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

#: Mirrors ``models.enums.MlClassification``. Binary on purpose: this is a
#: prototype's guess, not a graded measurement like ``movement_status``.
ML_CLASSES = ("NORMAL", "SUSPICIOUS")


def _classes(column: str) -> str:
    """Render the vocabulary the way migration 0002's ``_check`` helper does.

    PostgreSQL normalises ``IN ('A', 'B')`` over a varchar column to an
    ``ANY (ARRAY[...]::character varying[])`` form, and the drift guard in
    ``tests/test_database_models.py`` parses the values back out of those
    casts. Spelling it any other way renders identically to a human and
    breaks that guard.
    """
    allowed = ", ".join(f"'{value}'" for value in ML_CLASSES)
    return f"{column} IN ({allowed})"


