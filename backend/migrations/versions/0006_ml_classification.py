"""Record the prototype ML classifier's opinion alongside the rule-based verdict.

The geofence module gained a machine-learning layer in this revision. Every fix
that the rule engine measures can now also be scored by a lightweight
classifier trained on synthetic telemetry, and its opinion is stored next to
the measurement: ``ml_classification``, ``ml_probability`` and
``ml_model_version``.

Three columns rather than one is the point of this migration.

* ``ml_probability`` because a bare label hides how weak the evidence was. A
  classifier saying ``SUSPICIOUS`` at 0.51 and one saying it at 0.99 are not
  making the same claim, and the difference decides how much attention a human
  reviewer should pay.
* ``ml_model_version`` because the artifact is regenerated by a script and can
  drift. Without the version stamped on the row, "this fix was flagged" stops
  being a reproducible statement the moment the model is retrained.

These columns are deliberately *not* allowed to overwrite ``movement_status``.
That column holds a measurement against a known boundary and stays
authoritative; the ML columns hold an estimate from a prototype trained on
synthetic data. Two CHECK constraints make the three stand or fall together, so
the table can never hold a verdict without the probability and version that
would let someone interpret or audit it.

All three are nullable, and NULL is a supported deployment state rather than an
error: a checkout without a trained artifact runs on rules alone. Nothing in the
security pipeline depends on this column being populated.

Revision ID: 0006
Revises: 0005
Create Date: 2026-09-08
"""

