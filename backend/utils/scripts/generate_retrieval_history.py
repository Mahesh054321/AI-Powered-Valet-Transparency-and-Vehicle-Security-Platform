"""Generate synthetic retrieval history for the MVP predictor.

Usage (from the ``backend`` directory, with the virtual environment active):

    python utils/scripts/generate_retrieval_history.py
    python utils/scripts/generate_retrieval_history.py --episodes 8000 --seed 42
    python utils/scripts/generate_retrieval_history.py --output storage/data/retrieval_history.json

Writes a labelled history the training script consumes. Kept as a separate step
from training so the exact rows a model was fitted on can be inspected, shared
and re-used: if generation and fitting happen in one command, nobody can tell
afterwards which data produced which artifact.

**Read this before using the output.** Every row is produced by
``ai/retrieval/dataset.py`` from a process that file defines. It is not
operational data and must not be described as such. The generated file records
that in its own metadata.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parents[2]
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))

from ai.retrieval.dataset import ZONE_PROFILES, generate_history  # noqa: E402
from ai.retrieval.features import RETRIEVAL_FEATURE_COLUMNS  # noqa: E402
from ai.retrieval.model import PROTOTYPE_DISCLAIMER  # noqa: E402

DEFAULT_OUTPUT = BACKEND_ROOT / "storage" / "data" / "retrieval_history.json"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--episodes", type=int, default=4000, help="rows to generate")
    parser.add_argument("--seed", type=int, default=20260909, help="generator seed")
    parser.add_argument("--span-days", type=int, default=90, help="days the history covers")
    parser.add_argument(
        "--test-fraction", type=float, default=0.25, help="fraction of time held out"
    )
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--sample",
        type=int,
        default=5,
        help="how many example rows to print (0 for none)",
    )
    args = parser.parse_args(argv)

    print("=" * 74)
    print("  Retrieval history generation - SYNTHETIC DATA")
    print("=" * 74)
    print(f"  episodes    : {args.episodes}")
    print(f"  seed        : {args.seed}")
    print(f"  span        : {args.span_days} days")
    print(f"  held out    : last {args.test_fraction:.0%} of the time span")
    print()
    print("  Every row below is generated by ai/retrieval/dataset.py from a")
    print("  process that file defines. It is not operational data.")

    dataset = generate_history(
        episodes=args.episodes,
        seed=args.seed,
        span_days=args.span_days,
        test_fraction=args.test_fraction,
    )
    summary = dataset.summary()

    print(f"\n  rows            : {summary['rows']}")
    print(f"    train         : {summary['train_rows']}")
    print(f"    test (held)   : {summary['test_rows']}")
    print(
        f"  actual minutes  : mean {summary['train_mean_minutes']:.2f}, "
        f"range {summary['min_minutes']:.1f}-{summary['max_minutes']:.1f}"
    )
    print("  split           : by time, so evaluation is on a later period")

    print("\n  Zone profiles used (the generator's stand-in for yard layout):")
    for index, profile in enumerate(ZONE_PROFILES):
        print(
            f"    [{index}] capacity {int(profile['capacity']):>2}, "
            f"walk scale {profile['walk_scale']:.2f}x"
        )

    print("\n  Feature columns:")
    for name in RETRIEVAL_FEATURE_COLUMNS:
        print(f"    {name}")

    if args.sample:
        print(f"\n  First {args.sample} rows:")
        for episode in dataset.episodes[: args.sample]:
            row = episode.as_row()
            print(
                f"    {row['requested_at']}  queue={int(row['queue_position'])}"
                f"/{int(row['queue_size'])} valets={int(row['active_valets'])} "
                f"zone={row['zone_index']} -> actual {row['actual_retrieval_minutes']} min"
            )

    written = args.output
    written.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "source": "synthetic - generated by ai/retrieval/dataset.py",
        "generator": {
            "episodes": args.episodes,
            "seed": args.seed,
            "span_days": args.span_days,
            "test_fraction": args.test_fraction,
        },
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "feature_columns": list(RETRIEVAL_FEATURE_COLUMNS),
        "summary": summary,
        "disclaimer": PROTOTYPE_DISCLAIMER,
        "rows": [episode.as_row() for episode in dataset.episodes],
    }
    written.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    size_kb = written.stat().st_size / 1024.0
    print(f"\nWrote {summary['rows']} rows to {written} ({size_kb:.0f} kB)")
    print("\nTrain a model from it with:")
    print("    python utils/scripts/train_retrieval_model.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
