/**
 * Vehicle condition assessment API.
 *
 * Wraps the drop-off/pickup capture endpoints, the condition report, the
 * manager verification action, and the synthetic demo. Every call goes through
 * `apiClient`, so responses are unwrapped and errors arrive in the shared
 * `{ status, code, message, details }` shape.
 */

import { apiGet, apiPatch, apiPost, apiUpload } from './apiClient'
import { ENDPOINTS } from './endpoints'

/**
 * Build the multipart body for a capture request.
 *
 * One angle per photo is sent as a parallel `angles` list. The backend rejects a
 * count mismatch rather than guessing, because silently applying one angle to a
 * mixed set would compare unrelated viewpoints and flag the whole vehicle.
 */
function buildCaptureForm({ custodyId, photos, notes, odometer, location }) {
  const form = new FormData()
  form.append('custody_id', custodyId)

  photos.forEach((photo) => {
    form.append('images', photo.file, photo.file.name)
    form.append('angles', photo.angle)
  })

  if (notes) form.append('notes', notes)
  if (odometer) form.append('odometer', String(odometer))
  if (location) form.append('location', location)

  return form
}

/**
 * Capture the drop-off photo set.
 *
 * This is the baseline every later comparison is measured against. Nothing is
 * compared at this stage - there is no "after" yet.
 */
export function captureDropOff(payload) {
  return apiUpload(ENDPOINTS.inspectionDropOff, buildCaptureForm(payload))
}

/**
 * Capture the pickup photo set.
 *
 * The backend compares each angle against its drop-off counterpart in the same
 * request, so the response already carries the candidate findings, the rendered
 * comparison composite and a per-finding evidence crop.
 */
export function capturePickup(payload) {
  return apiUpload(ENDPOINTS.inspectionPickup, buildCaptureForm(payload))
}

/**
 * The full condition report for a custody session: both photo sets, every
 * finding, and the rendered evidence.
 *
 * `custodyId` is the custody *session* id, not an inspection id.
 */
export function fetchConditionReport(custodyId) {
  return apiGet(ENDPOINTS.inspectionReport(custodyId))
}

/**
 * Confirm or reject one finding. Manager or administrator only.
 *
 * Passing `UNVERIFIED` reopens a finding, which clears the reviewer. Rejected
 * findings stay visible and marked dismissed: the audit trail keeps what the
 * algorithm thought even after a human disagreed.
 */
export function verifyDetection(detectionId, { status, notes }) {
  return apiPatch(ENDPOINTS.inspectionVerify(detectionId), {
    status,
    ...(notes ? { notes } : {}),
  })
}

/** Annotate notes or severity on a candidate finding. Staff only. */
export function annotateDetection(detectionId, { notes, severity }) {
  return apiPatch(ENDPOINTS.inspectionAnnotate(detectionId), {
    notes,
    ...(severity ? { severity } : {}),
  })
}

/** Submit a customer or operator dispute regarding inspection findings. */
export function disputeInspection(custodyId, { reason, notes, disputedDetectionIds }) {
  return apiPost(ENDPOINTS.inspectionDispute(custodyId), {
    reason,
    ...(notes ? { notes } : {}),
    ...(disputedDetectionIds ? { disputed_detection_ids: disputedDetectionIds } : {}),
  })
}

/** Resolve a dispute and close custody. Manager or administrator only. */
export function resolveDispute(custodyId, { notes }) {
  return apiPost(ENDPOINTS.inspectionResolveDispute(custodyId), { notes })
}

/** Re-run comparison pipeline between drop-off and pickup sets. Manager/admin only. */
export function recompareInspection(custodyId) {
  return apiPost(ENDPOINTS.inspectionRecompare(custodyId), {})
}

/** The synthetic demo catalogue, so the UI can build a scenario picker. */
export function fetchDemoScenarios() {
  return apiGet(ENDPOINTS.inspectionDemoScenarios)
}

/**
 * Run the real pipeline over a synthetic photo pair.
 *
 * The photographs are generated by OpenCV; the findings are genuine pipeline
 * output computed from those pixels, not canned results. The backend stores no
 * inspection rows, so this can be run repeatedly without polluting real custody
 * history.
 */
export function runDemoComparison(scenario) {
  return apiPost(ENDPOINTS.inspectionDemo, { scenario })
}

export default {
  annotateDetection,
  captureDropOff,
  capturePickup,
  disputeInspection,
  fetchConditionReport,
  fetchDemoScenarios,
  recompareInspection,
  resolveDispute,
  runDemoComparison,
  verifyDetection,
}
